"""Retrieval adapters for local development and Azure AI Search hybrid search."""
from __future__ import annotations

import json
from typing import Any
from urllib.error import URLError
from urllib.request import Request, urlopen

from .config import Settings


class RetrievalUnavailableError(RuntimeError):
    """Raised when the configured retrieval backend cannot provide evidence."""


class AzureOpenAIEmbeddingModel:
    """Generate query embeddings for the Azure AI Search vector retrieval path."""

    def __init__(self, settings: Settings) -> None:
        self.settings = settings
        if not (settings.azure_openai_endpoint and settings.azure_openai_api_key and settings.azure_openai_embedding_deployment):
            raise RetrievalUnavailableError("Azure OpenAI embedding deployment is not configured.")

    def embed(self, text: str) -> list[float]:
        url = (
            f"{self.settings.azure_openai_endpoint.rstrip('/')}/openai/deployments/"
            f"{self.settings.azure_openai_embedding_deployment}/embeddings?api-version="
            f"{self.settings.azure_openai_api_version}"
        )
        request = Request(
            url,
            data=json.dumps({"input": text}).encode("utf-8"),
            headers={"Content-Type": "application/json", "api-key": self.settings.azure_openai_api_key},
            method="POST",
        )
        try:
            with urlopen(request, timeout=30) as response:
                body = json.loads(response.read().decode("utf-8"))
            return body["data"][0]["embedding"]
        except (URLError, TimeoutError, OSError, KeyError, IndexError, TypeError, json.JSONDecodeError) as exc:
            raise RetrievalUnavailableError("Azure OpenAI did not return a query embedding.") from exc


class AzureAISearchRetriever:
    """Run an Azure AI Search semantic hybrid query against a transcript index.

    The index is expected to expose ``id``, ``content``, ``start_seconds`` and
    ``end_seconds`` fields plus a vector field named ``content_vector``. Query
    vectors are generated by the configured Azure OpenAI embedding deployment.
    """

    def __init__(self, settings: Settings | None = None) -> None:
        self.settings = settings or Settings.from_env()
        if not self.settings.azure_search_configured:
            raise RetrievalUnavailableError("Azure AI Search is not configured.")
        self.embedding_model = AzureOpenAIEmbeddingModel(self.settings)

    def search(self, question: str, top_k: int = 3, filter_expression: str | None = None) -> list[dict[str, Any]]:
        vector = self.embedding_model.embed(question)
        payload: dict[str, Any] = {
            "search": question,
            "vectorQueries": [{"kind": "vector", "vector": vector, "fields": "content_vector", "k": max(50, top_k)}],
            "top": top_k,
            "select": "id,content,start_seconds,end_seconds,source_type",
            "queryType": "semantic",
        }
        if self.settings.azure_search_semantic_configuration:
            payload["semanticConfiguration"] = self.settings.azure_search_semantic_configuration
        if filter_expression:
            payload["filter"] = filter_expression
        url = (
            f"{self.settings.azure_search_endpoint.rstrip('/')}/indexes/"
            f"{self.settings.azure_search_index}/docs/search?api-version="
            f"{self.settings.azure_search_api_version}"
        )
        request = Request(
            url,
            data=json.dumps(payload).encode("utf-8"),
            headers={"Content-Type": "application/json", "api-key": self.settings.azure_search_api_key},
            method="POST",
        )
        try:
            with urlopen(request, timeout=30) as response:
                body = json.loads(response.read().decode("utf-8"))
        except (URLError, TimeoutError, OSError, json.JSONDecodeError) as exc:
            raise RetrievalUnavailableError("Azure AI Search did not return retrieval results.") from exc
        results = []
        for index, document in enumerate(body.get("value", []), start=1):
            results.append({
                "chunk_id": str(document.get("id", f"azure-{index:02d}")),
                "text": str(document.get("content", "")),
                "start_seconds": int(document.get("start_seconds", 0)),
                "end_seconds": int(document.get("end_seconds", 0)),
                "score": float(document.get("@search.rerankerScore", document.get("@search.score", 0))),
            })
        return results
